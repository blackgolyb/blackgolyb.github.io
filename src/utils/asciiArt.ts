export function generateAsciiArt(text: string): string[] {
  const lines: string[] = Array(FONT_HEIGHT).fill("");
  const upperText = text.toUpperCase();

  for (const char of upperText) {
    const charLines = FONT_MAP[char] || FONT_MAP[" "];
    for (let i = 0; i < FONT_HEIGHT; i++) {
      lines[i] += charLines[i] + " ";
    }
  }

  return lines;
}

export function getAsciiArtDimensions(text: string): {
  width: number;
  height: number;
} {
  const lines = generateAsciiArt(text);
  return {
    width: lines[0].length,
    height: lines.length,
  };
}
